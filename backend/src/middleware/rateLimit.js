// จำกัดจำนวนครั้งที่ยิงเข้ามาต่อ IP — กันการเดารหัสผ่านรัว ๆ (brute force)
// และกันการสแปมสมัครบัญชี
//
// ทำไมต้องมี: ถ้าไม่จำกัด คนร้ายเขียนสคริปต์ลองรหัสผ่านได้ไม่จำกัดครั้ง
//            (audit เคยยิงผิด 15 ครั้งใน 1 วินาทีโดยไม่โดนบล็อกเลย)
//
// หมายเหตุ: ตัวนับเก็บในหน่วยความจำของเซิร์ฟเวอร์ตัวนี้
//          ถ้าอนาคตรันหลาย instance ควรเปลี่ยนไปเก็บที่ Redis (store กลาง)
//          แต่สำหรับตอนนี้ (instance เดียว) เพียงพอแล้ว
// -----------------------------------------------------------------------------
import rateLimit from 'express-rate-limit'

// ---- จุดที่อ่อนไหว: login / register ----
// อนุญาต 10 ครั้งต่อ 15 นาทีต่อ IP
// (คนใช้จริงพิมพ์รหัสผิดไม่กี่ครั้งก็ถึงแล้ว 10 ครั้งจึงเหลือเฟือ
//  แต่สคริปต์เดารหัสที่ยิงเป็นพัน ๆ ครั้งจะโดนบล็อกทันที)
export const authLimiter = rateLimit({
  windowMs: 15 * 60 * 1000, // 15 นาที
  max: 10,
  standardHeaders: true,    // ส่ง header RateLimit-* บอกโควตาที่เหลือ
  legacyHeaders: false,
  // ข้อความเป็นรูปแบบเดียวกับ error อื่นของ API (ฝั่งเว็บอ่าน .message ได้เลย)
  message: {
    ok: false,
    message: 'พยายามเข้าสู่ระบบบ่อยเกินไป กรุณารอสักครู่แล้วลองใหม่',
  },
})
