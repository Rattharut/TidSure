// vite.config.js
// -----------------------------------------------------------------------------
// ไฟล์ตั้งค่าของ Vite (ตัว build/dev server ที่เร็วสำหรับ React)
// - plugin react() ทำให้ Vite เข้าใจไฟล์ .jsx และรองรับ Fast Refresh (แก้โค้ดแล้วเห็นผลทันที)
// - server.port กำหนดพอร์ตของ dev server ตอนรัน `npm run dev`
// ปกติแล้วคุณแทบไม่ต้องแก้ไฟล์นี้ ยกเว้นอยากเปลี่ยนพอร์ตหรือเพิ่ม proxy ไป backend ทีหลัง
// -----------------------------------------------------------------------------
import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    // strictPort: true = ถ้าพอร์ต 5173 ไม่ว่าง ให้ "ฟ้อง error" ไปเลย
    // ห้ามแอบย้ายไปพอร์ตอื่นเงียบ ๆ
    // (เคยเจอปัญหา: มี dev server เก่าค้างที่ 5173 ตัวใหม่เลยไปอยู่ 5174
    //  พอเปิดเบราว์เซอร์ที่ 5173 ก็เห็นโค้ดเก่า งงว่าทำไมแก้แล้วไม่เปลี่ยน)
    strictPort: true,
    open: true, // เปิดเบราว์เซอร์ให้อัตโนมัติเมื่อรัน dev
    // ------------------------------------------------------------------
    // proxy: เมื่อเว็บเรียก fetch('/api/...') Vite จะส่งต่อไปให้ backend ที่พอร์ต 5000
    // ข้อดี: ฝั่งเว็บเขียน '/api/auth/login' สั้น ๆ ได้เลย ไม่ต้องใส่ http://localhost:5000
    //        และไม่เจอปัญหา CORS ตอนพัฒนา
    // *** ต้องเปิด backend ไว้ด้วย (cd backend && npm run dev) ไม่งั้น API จะเรียกไม่ติด ***
    proxy: {
      '/api': 'http://localhost:5000',
    },
    // ------------------------------------------------------------------
  },
})
