// สเปกสีจากผู้ใช้:
//   โครงสร้างคือ "พื้นสีทึบ + ขอบเรืองแสง" ไม่ใช่การไล่เฉดจางไปหาขาว
//
//   ง่าย     -> เขียว  (พื้นเขียวสด ขอบเขียวอ่อนเรืองแสง)
//   ปานกลาง -> เหลือง (พื้นเหลืองสด ขอบเหลืองอ่อนเรืองแสง)
//   ยาก      -> แดง    (พื้นเกือบดำ ขอบแดงเลือดหมูเรืองแสง)
//
// อ่านออกทันทีแบบสัญญาณไฟจราจร เขียว = ปลอดภัย แดง = หนัก
// โดยไม่ต้องดูคำอธิบายสีก่อน
//
// สังเกตว่าระดับยากกลับด้านกับอีกสองระดับ:
//   สองระดับแรกพื้นสดขอบอ่อน ส่วนยากพื้นมืดขอบสด
//   ทำให้ระดับยากดูอันตรายและแยกออกจากอีกสองระดับทันที
//
// -----------------------------------------------------------------------------
// แต่ละระดับเก็บ 4 สี แยกหน้าที่กันชัดเจน อย่าเอาไปใช้สลับกัน:
//
//   core  = สีตรงกลางกราฟ (โคนก้านแกน) โทนเข้มกว่า ใช้สร้างมิติ
//   solid = "สีประจำวิชา" ใช้ที่ปลายก้านแกนและเส้นรอบรูปหกเหลี่ยม
//           สีนี้คือตัวเชื่อมให้ก้านแกนกับเส้นรอบรูปบรรจบกันแบบไร้รอยต่อ
//   edge  = สีขอบและแสงเรือง
//   text  = สีสำหรับ "ตัวหนังสือ" โดยเฉพาะ
//
// ทำไม text ต้องแยกจาก solid:
//   ระดับยากใช้ solid = #e01029 ซึ่งบนพื้นหลังเข้มได้ contrast แค่ประมาณ 3.4:1
//   ไม่ผ่านเกณฑ์ WCAG AA (ต้อง 4.5:1 สำหรับตัวหนังสือขนาดปกติ)
//   จึงต้องมีสีอ่อนกว่าไว้ใช้กับตัวอักษรโดยเฉพาะ ส่วนเส้นกราฟใช้ solid ได้
//   เพราะเกณฑ์ของกราฟิกอยู่ที่ 3:1 ไม่ใช่ 4.5:1
//
// rank = อันดับความยาก ต้องตรงกับ DIFFICULTY_RANK ใน
//        backend/src/controllers/statusController.js
// -----------------------------------------------------------------------------

