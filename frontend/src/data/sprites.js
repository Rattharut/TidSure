// =============================================================================
// คำนวณ scale จาก "ความสูงที่อยากได้บนจอ"
// =============================================================================
// ทำไมไม่ใช้ scale ตรง ๆ:
//   มอนแต่ละตัวขนาดเฟรมไม่เท่ากัน (สไลม์สูง 197 ก็อบลินสูง 220)
//   ถ้าใช้ scale เดียวกันทั้งคู่ ตัวที่เฟรมใหญ่จะล้นกรอบฉากต่อสู้
//   และเวลาเพิ่มมอนตัวใหม่ต้องมานั่งลองค่า scale ใหม่ทุกครั้ง
//
//   คุมด้วยความสูงแทน -> ระบุได้ตรง ๆ ว่าอยากให้ตัวนี้สูงกี่พิกเซลบนจอ
//   เพิ่มมอนตัวใหม่ก็แค่ใส่ stageHeight ไม่ต้องคำนวณเอง
export function getStageScale(spriteName) {
  const spec = SPRITES[spriteName]
  if (!spec) return 1
  return spec.stageHeight / spec.idle.frameHeight
}

