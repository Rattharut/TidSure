// ว่าด่านไหนขาดสไปรต์ตัวไหนอยู่
//
// ลำดับใน array ตรงกับ monster.index ใน dungeonEngine
// (2 ตัวแรกเป็น kind 'normal' ตัวสุดท้ายเป็น 'boss')
const STAGE_MONSTERS = {
  'ง่าย':     ['slime', 'goblin', 'orc'],       // ← บอสด่านง่าย = ออร์ค
  'ปานกลาง': ['deepone', 'siren', 'seaserpent'], // ← ปลาน้ำลึก · ไซเรน · บอสงูทะเล
  'ยาก':      ['scorpion', 'bandit', 'worm'],   // ← แมงป่อง · โจร · บอสหนอนยักษ์
}

// =============================================================================
// จับคู่ "มอนในเกม" -> "สไปรต์ที่จะใช้วาด"
// =============================================================================
// คืน null = ให้หน้าเกมใช้กล่อง placeholder แทน ไม่ใช่จอว่าง
//
// วิธีเพิ่มมอนตัวใหม่ในอนาคต:
//   1. วางไฟล์สไปรต์ใน src/assets/sprites/
//   2. เพิ่มสเปกใน SPRITES ข้างบน (ขนาดเฟรม จำนวนเฟรม ความเร็ว เงา)
//   3. ใส่ชื่อลงในช่องที่ต้องการใน STAGE_MONSTERS
//   ไม่ต้องแก้ MonsterSprite.jsx / BattleStage.jsx / CSS เลยสักบรรทัด
//
// รับ: { difficulty, index } จาก monster ใน dungeonEngine
//   index = ลำดับตัวในด่าน (0, 1, 2)
export function resolveMonsterSprite({ difficulty, index }) {
  return STAGE_MONSTERS[difficulty]?.[index] ?? null
}
