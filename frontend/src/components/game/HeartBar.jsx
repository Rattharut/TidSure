// แถบ HP — พลังชีวิตของผู้เล่น / Monster / บอส
//
// สไตล์: HUD แบบเกม 8-bit
//   คำว่า "HP"  = ฟอนต์ pixel สีขาว ตัวใหญ่ อ่านชัด
//   หัวใจ       = IconHeartPixel วาดด้วยสี่เหลี่ยมล้วน ไม่มีเส้นโค้ง
//   กรอบ        = แผงสีดำโปร่งคลุมหัวใจไว้ ให้ดูเป็น HUD ของเกม
//                 และช่วยให้หัวใจอ่านออกไม่ว่าพื้นหลังฉากจะสว่างหรือมืด
//
// props:
//   current  = หัวใจที่เหลืออยู่ตอนนี้
//   max      = หัวใจเต็ม
//   tone     = สีของหัวใจ: 'rose' (ผู้เล่นปกติ) | 'gold' (หัวใจสีทอง) | 'danger' (Monster)
//   srLabel  = บอกว่านี่คือ HP ของใคร สำหรับโปรแกรมอ่านหน้าจอเท่านั้น
//
// -----------------------------------------------------------------------------
// *** เรื่องตัวเลข 5/5 ***
// -----------------------------------------------------------------------------
// ไม่แสดงบนจอแล้ว เพราะนับหัวใจเอาก็รู้ และเลขทำให้ HUD รกโดยไม่จำเป็น
//
// แต่ยังต้องมีในโค้ดแบบซ่อนไว้ (sr-only) เพราะถ้าตัดทิ้งจริง ๆ
// คนที่ใช้โปรแกรมอ่านหน้าจอจะเหลือข้อมูลแค่ "HP" ลอย ๆ
// ไม่รู้เลยว่าเหลือเท่าไร เพราะเขามองไม่เห็นหัวใจที่วาดไว้
// -----------------------------------------------------------------------------
import { IconHeartPixel } from '../icons/index.jsx'

const TONES = {
  rose:   'text-rose',
  gold:   'text-gold',
  danger: 'text-danger',
  // แดงดำ — หัวใจของมังกร (บอสโหมดจำกัดเวลา) แดงเข้มหม่นเลือด ดูดุน่าเกรงขาม
  dragon: 'text-[#8f1414]',
}

export default function HeartBar({ current, max, tone = 'rose', srLabel }) {
  return (
    <div className="flex items-center gap-2">
      {/* ---- คำว่า HP ----
          สีขาวล้วนเพื่อให้เด่นสุดบนฉากต่อสู้ (ตัวอื่นใน HUD ใช้สีเทา)
          drop-shadow ช่วยให้ตัวหนังสือลอยออกจากพื้นหลังฉากที่อาจสว่าง */}
      <span
        className="font-pixel text-[11px] leading-none text-white"
        style={{ textShadow: '2px 2px 0 rgba(0,0,0,0.85)' }}
      >
        HP
      </span>

      {/* ---- กรอบดำคลุมหัวใจ ----
          ring ด้านนอกทำหน้าที่เป็นขอบเข้ม ให้แผงดูมีน้ำหนักแบบ HUD เกม
          bg ดำโปร่งทำให้หัวใจสีแดงตัดขึ้นมาชัดไม่ว่าพื้นหลังจะเป็นสีอะไร */}
      <div className="flex items-center gap-1 rounded-md bg-black/55 px-2 py-1 ring-1 ring-white/15">
        {Array.from({ length: max }).map((_, i) => (
          <IconHeartPixel
            key={i}
            className={`h-4 w-4 ${i < current ? TONES[tone] : 'text-white/20'}`}
          />
        ))}
      </div>

      {/* ตัวเลขซ่อนไว้ให้โปรแกรมอ่านหน้าจอเท่านั้น (ดูคำอธิบายด้านบน) */}
      <span className="sr-only">
        {srLabel} เหลือ {current} จาก {max}
      </span>
    </div>
  )
}
